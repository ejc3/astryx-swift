// Resolves every theme in src/themes.ts with Astryx's own resolver and writes
// src/themes.generated.ts: concrete colors (#RRGGBBAA) and sizes (points), per mode.
// Run after changing src/themes.ts or upgrading @astryxdesign/core: `pnpm themes`.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { defineTheme } from "@astryxdesign/core/theme";
import { resolveThemeTokens } from "@astryxdesign/core/theme/tokens";
import { THEME_INPUTS } from "../src/themes.ts";

const KEEP = /^--(color-|spacing-|radius-|font-size-|font-weight-|text-(heading|body|label)-)/;
const REM = 16;

function hex2(n) { return Math.round(n).toString(16).padStart(2, "0").toUpperCase(); }

/** A CSS color as #RRGGBBAA, or null when it is not one. */
export function color(value) {
  const v = value.trim();
  let m = /^#([0-9a-f]{3,8})$/i.exec(v);
  if (m) {
    let h = m[1];
    if (h.length === 3 || h.length === 4) h = [...h].map((c) => c + c).join("");
    if (h.length === 6) h += "FF";
    return h.length === 8 ? `#${h.toUpperCase()}` : null;
  }
  m = /^rgba?\(\s*([\d.]+)[,\s]+([\d.]+)[,\s]+([\d.]+)(?:[,\s/]+([\d.]+%?))?\s*\)$/i.exec(v);
  if (m) {
    const a = m[4] === undefined ? 1 : m[4].endsWith("%") ? parseFloat(m[4]) / 100 : parseFloat(m[4]);
    return `#${hex2(+m[1])}${hex2(+m[2])}${hex2(+m[3])}${hex2(a * 255)}`;
  }
  if (v === "transparent") return "#00000000";
  return null;
}

/** A CSS length as points, or null. */
export function length(value) {
  const m = /^(-?[\d.]+)(rem|px)?$/.exec(value.trim());
  if (!m) return null;
  return m[2] === "rem" ? parseFloat(m[1]) * REM : parseFloat(m[1]);
}

function resolve(input, mode) {
  const theme = defineTheme({ name: `an-${input.id}`, tokens: Object.fromEntries(
    Object.entries(input.tokens).map(([k, v]) => [k, Array.isArray(v) ? [...v] : v])) });
  const all = resolveThemeTokens(theme, { mode });
  const colors = {}, sizes = {};
  for (const [name, value] of Object.entries(all)) {
    if (!KEEP.test(name) || typeof value !== "string") continue;
    const key = name.slice(2);
    if (key.startsWith("color-")) { const c = color(value); if (c) colors[key] = c; }
    else { const n = length(value); if (n !== null) sizes[key] = n; }
  }
  return { colors, sizes };
}

const out = {
  source: "@astryxdesign/core 0.7.1, resolveThemeTokens",
  themes: THEME_INPUTS.map((t) => ({ id: t.id, label: t.label, light: resolve(t, "light"), dark: resolve(t, "dark") })),
};
const path = fileURLToPath(new URL("../src/themes.generated.ts", import.meta.url));
writeFileSync(path, `// Generated by scripts/themes.mjs from ${out.source}. Do not edit: change src/themes.ts and run \`pnpm themes\`.
import type { ThemesFile } from "./themes.ts";

export const THEMES: ThemesFile = ${JSON.stringify(out, null, 1)};
`);
const first = out.themes[0];
console.log(`${out.themes.length} themes, ${Object.keys(first.light.colors).length} colors and ${Object.keys(first.light.sizes).length} sizes each -> ${path}`);
